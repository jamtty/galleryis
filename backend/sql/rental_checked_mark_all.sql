UPDATE `g4_write_order`
SET `rt_checked`    = 1,
    `rt_checked_at` = NOW()
WHERE `rt_checked` = 0;

-- 확인 — 0건(확인전)은 새 신청이 없는 상태입니다.
SELECT `rt_checked` AS 확인여부, COUNT(*) AS 건수
FROM `g4_write_order`
GROUP BY `rt_checked`;
